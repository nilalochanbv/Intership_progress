
# Python Day 1 - Variables, Data Types and Strings

# 1. Integer
age = 21
print("Age:", age)

# 2. Float
height = 5.8
print("Height:", height)

# 3. String
name = "Nilalochan"
print("Name:", name)

# 4. Boolean
is_student = True
print("Is student:", is_student)

# 5. Type checking
print("Type of age:", type(age).__name__)

# 6. String concatenation
first_name = "Nila"
last_name = "lochan"
print("Full name:", first_name + " " + last_name)

# 7. F-string
print(f"My name is {name} and my age is {age}.")

# 8. String methods
language = "python programming"
print("Uppercase:", language.upper())

# 9. String slicing
word = "Python"
print("First three characters:", word[:3])

# 10. String length
message = "Hello World"
print("Message length:", len(message))
